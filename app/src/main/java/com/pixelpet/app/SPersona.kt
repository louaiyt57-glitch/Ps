package com.pixelpet.app

/**
 * هوية كل عود: طباع ثابتة تُقرأ من حركة الجسم وحده (بلا رموز ولا كلام).
 * تؤثر في تفاوت الحركات الحلقية واختيار الأدوار داخل المشاهد.
 */
enum class SPersona {
    BRAVE,   // شجاع: يبادر ويقف في المقدمة
    SHY,     // خجول: يتأخر خطوة ويجلس على الأطراف
    JOVIAL,  // مرح: أول من يرقص ويصفق
    COOL,    // هادئ: بطيء الإيماء وواثق
    GRUMPY;  // عابس: يتشنج ويتذمر ثم ينجح مع الآخرين

    companion object {
        fun fromId(id: Int) = entries[id % entries.size]
    }
}
